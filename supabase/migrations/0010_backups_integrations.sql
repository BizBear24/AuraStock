-- -------------------------------------------------------------- stock analysis
-- Per active product: usage and receipts in the last p_days, number of movements and the last one.
-- Classification (fast/slow/dead), days of cover and reorder suggestions are computed in src/domain/analysis.ts.
create or replace function public.stock_analysis(inv uuid, p_days integer default 30)
returns table (
  product_id uuid, name text, sku text, unit text, category text, quantity numeric, min_stock numeric,
  units_out numeric, units_in numeric, movements bigint, last_movement_at timestamptz, expires_on date
)
language sql stable as $$
  select p.id, p.name, p.sku, p.unit, c.name, p.quantity, p.min_stock,
         coalesce(sum(-m.delta) filter (where m.movement_type = 'out' and m.created_at >= now() - make_interval(days => p_days)), 0),
         coalesce(sum(m.delta) filter (where m.movement_type = 'in' and m.created_at >= now() - make_interval(days => p_days)), 0),
         count(m.id) filter (where m.created_at >= now() - make_interval(days => p_days)),
         max(m.created_at),
         p.expires_on
  from public.products p
  left join public.categories c on c.id = p.category_id
  left join public.stock_movements m on m.product_id = p.id
  where p.inventory_id = inv and p.archived_at is null
  group by p.id, c.name
  order by p.name
$$;

