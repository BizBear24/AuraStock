grant execute on function public.remove_integration(uuid, text) to authenticated;

-- ------------------------------------------------------------------ storage
-- Private bucket for backup files, one folder per organization: backups/<organization id>/<backup id>.json.
-- Only admins and owners of that organization can read, write or delete its files.
-- (Skipped where Supabase Storage is not installed, e.g. in the local test database.)
do $$
begin
  if exists (select 1 from information_schema.tables where table_schema = 'storage' and table_name = 'buckets') then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('backups', 'backups', false, 52428800, array['application/json'])
    on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

    drop policy if exists aurastock_backups_select on storage.objects;
    drop policy if exists aurastock_backups_insert on storage.objects;
    drop policy if exists aurastock_backups_delete on storage.objects;
    create policy aurastock_backups_select on storage.objects for select to authenticated
      using (bucket_id = 'backups' and public.has_org_role(public.try_uuid((storage.foldername(name))[1]), 'admin'));
    create policy aurastock_backups_insert on storage.objects for insert to authenticated
      with check (bucket_id = 'backups' and public.has_org_role(public.try_uuid((storage.foldername(name))[1]), 'admin'));
    create policy aurastock_backups_delete on storage.objects for delete to authenticated
      using (bucket_id = 'backups' and public.has_org_role(public.try_uuid((storage.foldername(name))[1]), 'admin'));
  end if;
end $$;
