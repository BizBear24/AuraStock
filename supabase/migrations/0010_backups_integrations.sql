-- Phase 8: cloud backups (manual + scheduled), verified restore, Google Drive connection records,
-- NFC tag links on products, and the stock analysis report.
--
-- Backups are JSON snapshots of a whole organization produced by export_org_backup(). The browser uploads
-- the exact bytes to a private Storage bucket (or Google Drive), records the size and SHA-256 checksum, then
-- downloads the file again and checks it before marking the backup as verified. A backup is never trusted
-- just because the export query succeeded.
--
-- Restoring never overwrites live data: restore_backup() creates NEW inventories ("<name> (restored YYYY-MM-DD)")
-- and replays the stock ledger with its original timestamps, refusing the whole restore if any product's
-- history does not add up to its recorded quantity.

create or replace function public.try_uuid(p text) returns uuid
language plpgsql immutable as $$
begin
  return p::uuid;
exception when others then
  return null;
end $$;

-- ------------------------------------------------------------ backup records
alter table public.organizations add column backup_interval_days integer check (backup_interval_days in (1, 7));
alter table public.organizations add column auto_backup_claimed_at timestamptz;

create type public.backup_destination as enum ('supabase', 'google_drive');
create type public.backup_kind as enum ('manual', 'automatic');

create table public.backup_records (
  -- Generated by the client so the storage path is known before the upload starts.
  id uuid primary key,
  organization_id uuid not null references public.organizations (id) on delete cascade,
  kind public.backup_kind not null,
  destination public.backup_destination not null,
  storage_path text,
  external_id text,
  size_bytes bigint not null check (size_bytes > 0),
  sha256 text not null check (sha256 ~ '^[0-9a-f]{64}$'),
  format_version integer not null,
  counts jsonb not null default '{}'::jsonb,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  verified_at timestamptz,
  verify_error text,
  check ((destination = 'supabase' and storage_path is not null) or (destination = 'google_drive' and external_id is not null))
);
create index backup_records_org_idx on public.backup_records (organization_id, created_at desc);

alter table public.backup_records enable row level security;
create policy backup_records_select on public.backup_records for select to authenticated
  using (public.has_org_role(organization_id, 'admin'));
revoke insert, update, delete, truncate on public.backup_records from anon, authenticated;

-- Everything an organization owns, as one JSON document (format "aurastock-backup", version 1).
create or replace function public.export_org_backup(p_org uuid) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  doc jsonb;
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode = '28000';
  end if;
  if not public.has_org_role(p_org, 'admin') then
    raise exception 'Only admins and owners can create backups' using errcode = '42501';
  end if;

  select jsonb_build_object(
    'format', 'aurastock-backup',
    'version', 1,
    'created_at', now(),
    'organization', (select jsonb_build_object('id', o.id, 'name', o.name) from public.organizations o where o.id = p_org),
    'inventories', coalesce((select jsonb_agg(to_jsonb(i) order by i.created_at, i.id) from public.inventories i where i.organization_id = p_org), '[]'::jsonb),
    'categories', coalesce((select jsonb_agg(to_jsonb(c) order by c.name, c.id) from public.categories c join public.inventories i on i.id = c.inventory_id where i.organization_id = p_org), '[]'::jsonb),
    'tags', coalesce((select jsonb_agg(to_jsonb(t) order by t.name, t.id) from public.tags t join public.inventories i on i.id = t.inventory_id where i.organization_id = p_org), '[]'::jsonb),
    'products', coalesce((select jsonb_agg(to_jsonb(p) - 'stock_state' order by p.created_at, p.id) from public.products p join public.inventories i on i.id = p.inventory_id where i.organization_id = p_org), '[]'::jsonb),
    'product_tags', coalesce((select jsonb_agg(to_jsonb(pt)) from public.product_tags pt join public.inventories i on i.id = pt.inventory_id where i.organization_id = p_org), '[]'::jsonb),
    'stock_movements', coalesce((select jsonb_agg(to_jsonb(m) order by m.created_at, m.id) from public.stock_movements m join public.inventories i on i.id = m.inventory_id where i.organization_id = p_org), '[]'::jsonb),
    'transfers', coalesce((select jsonb_agg(to_jsonb(t) order by t.dispatched_at, t.id) from public.transfers t where t.organization_id = p_org), '[]'::jsonb),
    'transfer_lines', coalesce((select jsonb_agg(to_jsonb(l)) from public.transfer_lines l join public.transfers t on t.id = l.transfer_id where t.organization_id = p_org), '[]'::jsonb)
  ) into doc;
  return doc;
end $$;

create or replace function public.register_backup(
  p_org uuid,
  p_id uuid,
  p_kind public.backup_kind,
  p_destination public.backup_destination,
  p_storage_path text,
  p_external_id text,
  p_size bigint,
  p_sha256 text,
  p_format_version integer,
  p_counts jsonb
) returns void
language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode = '28000';
  end if;
  if not public.has_org_role(p_org, 'admin') then
    raise exception 'Only admins and owners can create backups' using errcode = '42501';
  end if;
  if p_destination = 'supabase' and p_storage_path is distinct from (p_org::text || '/' || p_id::text || '.json') then
    raise exception 'Unexpected storage path for this backup' using errcode = '22023';
  end if;
  insert into public.backup_records (id, organization_id, kind, destination, storage_path, external_id, size_bytes, sha256, format_version, counts, created_by)
  values (p_id, p_org, p_kind, p_destination, p_storage_path, p_external_id, p_size, lower(p_sha256), p_format_version, coalesce(p_counts, '{}'::jsonb), auth.uid());
  insert into public.audit_logs (organization_id, actor_id, action, entity_type, entity_id, details)
  values (p_org, auth.uid(), 'backup.create', 'backup', p_id,
          jsonb_build_object('kind', p_kind, 'destination', p_destination, 'size', p_size, 'counts', p_counts));
end $$;

create or replace function public.mark_backup_verified(p_backup uuid, p_ok boolean, p_error text default null) returns void
language plpgsql security definer set search_path = public as $$
declare
  rec public.backup_records%rowtype;
begin
  select * into rec from public.backup_records where id = p_backup;
  if not found or not public.has_org_role(rec.organization_id, 'admin') then
    raise exception 'Backup not found or you do not have permission' using errcode = '42501';
  end if;
  update public.backup_records
    set verified_at = case when p_ok then now() else null end,
        verify_error = case when p_ok then null else left(coalesce(p_error, 'Verification failed'), 500) end
    where id = p_backup;
end $$;

create or replace function public.delete_backup_record(p_backup uuid) returns void
language plpgsql security definer set search_path = public as $$
declare
  rec public.backup_records%rowtype;
begin
  select * into rec from public.backup_records where id = p_backup;
  if not found or not public.has_org_role(rec.organization_id, 'admin') then
    raise exception 'Backup not found or you do not have permission' using errcode = '42501';
  end if;
  delete from public.backup_records where id = p_backup;
  insert into public.audit_logs (organization_id, actor_id, action, entity_type, entity_id, details)
  values (rec.organization_id, auth.uid(), 'backup.delete', 'backup', p_backup, jsonb_build_object('kind', rec.kind, 'destination', rec.destination));
end $$;

-- p_days: null (off), 1 (daily) or 7 (weekly).
create or replace function public.set_backup_schedule(p_org uuid, p_days integer) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.has_org_role(p_org, 'admin') then
    raise exception 'Only admins and owners can change the backup schedule' using errcode = '42501';
  end if;
  if p_days is not null and p_days not in (1, 7) then
    raise exception 'Choose daily or weekly backups' using errcode = '22023';
  end if;
  update public.organizations set backup_interval_days = p_days where id = p_org;
  insert into public.audit_logs (organization_id, actor_id, action, entity_type, entity_id, details)
  values (p_org, auth.uid(), 'backup.schedule', 'organization', p_org, jsonb_build_object('days', p_days));
end $$;

-- True exactly once per due period: when a scheduled backup is due and nobody else has started it in the last
-- 15 minutes. Lets any admin's open app take the backup without two tabs or two people doing it twice.
create or replace function public.claim_auto_backup(p_org uuid) returns boolean
language plpgsql security definer set search_path = public as $$
declare
  org public.organizations%rowtype;
  last_at timestamptz;
begin
  if not public.has_org_role(p_org, 'admin') then
    return false;
  end if;
  select * into org from public.organizations where id = p_org for update;
  if org.backup_interval_days is null then
    return false;
  end if;
  select max(created_at) into last_at from public.backup_records where organization_id = p_org and kind = 'automatic';
  if last_at is not null and last_at > now() - make_interval(days => org.backup_interval_days) then
    return false;
  end if;
  if org.auto_backup_claimed_at is not null and org.auto_backup_claimed_at > now() - interval '15 minutes' then
    return false;
  end if;
  update public.organizations set auto_backup_claimed_at = now() where id = p_org;
  return true;
end $$;

-- ----------------------------------------------------------------- restore
create or replace function public.restore_backup(p_org uuid, p_backup jsonb, p_inventory_ids uuid[] default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
  inv jsonb;
  c jsonb;
  t jsonb;
  p jsonb;
  pt jsonb;
  m jsonb;
  new_id uuid;
  base_name text;
  final_name text;
  n int;
  inv_map jsonb := '{}'::jsonb;
  cat_map jsonb := '{}'::jsonb;
  tag_map jsonb := '{}'::jsonb;
  prod_map jsonb := '{}'::jsonb;
  prod_inv jsonb := '{}'::jsonb;
  mv_map jsonb := '{}'::jsonb;
  restored jsonb := '[]'::jsonb;
  actor uuid;
  pid_txt text;
  items jsonb[];
  i int;
  j int;
  found_j int;
  tmp jsonb;
  bal numeric;
  new_pid uuid;
  n_products int := 0;
  n_movements int := 0;
begin
  if uid is null then
    raise exception 'Authentication required' using errcode = '28000';
  end if;
  if not public.has_org_role(p_org, 'admin') then
    raise exception 'Only admins and owners can restore backups' using errcode = '42501';
  end if;
  if p_backup is null or p_backup ->> 'format' is distinct from 'aurastock-backup' then
    raise exception 'This file is not an AuraStock backup' using errcode = '22023';
  end if;
  if (p_backup ->> 'version') is distinct from '1' then
    raise exception 'Unsupported backup version %', p_backup ->> 'version' using errcode = '22023';
  end if;

  perform set_config('app.stock_write', 'on', true);

  -- Inventories: always created new, with a distinct name.
  for inv in select value from jsonb_array_elements(coalesce(p_backup -> 'inventories', '[]'::jsonb)) loop
    if p_inventory_ids is not null and not (public.try_uuid(inv ->> 'id') = any (p_inventory_ids)) then
      continue;
    end if;
    base_name := left(inv ->> 'name', 50) || ' (restored ' || to_char(now(), 'YYYY-MM-DD') || ')';
    final_name := base_name;
    n := 1;
    while exists (select 1 from public.inventories where organization_id = p_org and name = final_name) loop
      n := n + 1;
      final_name := base_name || ' ' || n;
    end loop;
    insert into public.inventories (organization_id, name, description, created_by)
    values (p_org, final_name, inv ->> 'description', uid) returning id into new_id;
    inv_map := inv_map || jsonb_build_object(inv ->> 'id', new_id);
    restored := restored || jsonb_build_array(jsonb_build_object('old_id', inv ->> 'id', 'new_id', new_id, 'name', final_name));
  end loop;
  if inv_map = '{}'::jsonb then
    raise exception 'Nothing to restore: the backup has no matching inventories' using errcode = '22023';
  end if;

  for c in select value from jsonb_array_elements(coalesce(p_backup -> 'categories', '[]'::jsonb)) loop
    continue when not inv_map ? (c ->> 'inventory_id');
    insert into public.categories (inventory_id, name) values ((inv_map ->> (c ->> 'inventory_id'))::uuid, c ->> 'name') returning id into new_id;
    cat_map := cat_map || jsonb_build_object(c ->> 'id', new_id);
  end loop;

  for t in select value from jsonb_array_elements(coalesce(p_backup -> 'tags', '[]'::jsonb)) loop
    continue when not inv_map ? (t ->> 'inventory_id');
    insert into public.tags (inventory_id, name) values ((inv_map ->> (t ->> 'inventory_id'))::uuid, t ->> 'name') returning id into new_id;
    tag_map := tag_map || jsonb_build_object(t ->> 'id', new_id);
  end loop;

  for p in select value from jsonb_array_elements(coalesce(p_backup -> 'products', '[]'::jsonb)) loop
    continue when not inv_map ? (p ->> 'inventory_id');
    select id into actor from public.profiles where id = public.try_uuid(p ->> 'created_by');
    insert into public.products (inventory_id, name, sku, barcode, qr_code, nfc_uid, description, category_id, unit, min_stock, expires_on, created_by, created_at)
    values (
      (inv_map ->> (p ->> 'inventory_id'))::uuid, p ->> 'name', p ->> 'sku', p ->> 'barcode', p ->> 'qr_code', p ->> 'nfc_uid', p ->> 'description',
      case when p ->> 'category_id' is null then null else (cat_map ->> (p ->> 'category_id'))::uuid end,
      coalesce(p ->> 'unit', 'pcs'), coalesce((p ->> 'min_stock')::numeric, 0), (p ->> 'expires_on')::date,
      coalesce(actor, uid), coalesce((p ->> 'created_at')::timestamptz, now())
    ) returning id into new_id;
    prod_map := prod_map || jsonb_build_object(p ->> 'id', new_id);
    prod_inv := prod_inv || jsonb_build_object(p ->> 'id', inv_map ->> (p ->> 'inventory_id'));
    n_products := n_products + 1;
  end loop;

  for pt in select value from jsonb_array_elements(coalesce(p_backup -> 'product_tags', '[]'::jsonb)) loop
    continue when not (prod_map ? (pt ->> 'product_id') and tag_map ? (pt ->> 'tag_id'));
    insert into public.product_tags (product_id, tag_id, inventory_id)
    values ((prod_map ->> (pt ->> 'product_id'))::uuid, (tag_map ->> (pt ->> 'tag_id'))::uuid, (prod_inv ->> (pt ->> 'product_id'))::uuid)
    on conflict do nothing;
  end loop;

  -- Replay each product's ledger in time order, checking that every balance chains from zero. Movements that
  -- share a timestamp are put in the only order their balances allow.
  for pid_txt in
    select distinct value ->> 'product_id' from jsonb_array_elements(coalesce(p_backup -> 'stock_movements', '[]'::jsonb))
    where prod_map ? (value ->> 'product_id')
  loop
    items := array(
      select value from jsonb_array_elements(p_backup -> 'stock_movements')
      where value ->> 'product_id' = pid_txt
      order by (value ->> 'created_at')::timestamptz, value ->> 'id'
    );
    bal := 0;
    for i in 1 .. coalesce(array_length(items, 1), 0) loop
      if (items[i] ->> 'quantity_before')::numeric <> bal then
        found_j := null;
        for j in i + 1 .. array_length(items, 1) loop
          exit when (items[j] ->> 'created_at')::timestamptz <> (items[i] ->> 'created_at')::timestamptz;
          if (items[j] ->> 'quantity_before')::numeric = bal then
            found_j := j;
            exit;
          end if;
        end loop;
        if found_j is null then
          raise exception 'The backup''s stock history is inconsistent (movement %). Nothing was restored.', items[i] ->> 'id' using errcode = '22023';
        end if;
        tmp := items[i];
        items[i] := items[found_j];
        items[found_j] := tmp;
      end if;
      m := items[i];
      if (m ->> 'quantity_after')::numeric <> bal + (m ->> 'delta')::numeric then
        raise exception 'The backup''s stock history is inconsistent (movement %). Nothing was restored.', m ->> 'id' using errcode = '22023';
      end if;
      select id into actor from public.profiles where id = public.try_uuid(m ->> 'created_by');
      insert into public.stock_movements (
        inventory_id, product_id, movement_type, delta, quantity_before, quantity_after,
        reference, note, operation_id, corrects_movement_id, created_by, created_at
      ) values (
        (prod_inv ->> pid_txt)::uuid, (prod_map ->> pid_txt)::uuid, (m ->> 'movement_type')::public.movement_type,
        (m ->> 'delta')::numeric, (m ->> 'quantity_before')::numeric, (m ->> 'quantity_after')::numeric,
        m ->> 'reference', m ->> 'note', coalesce(public.try_uuid(m ->> 'operation_id'), gen_random_uuid()),
        case when m ->> 'corrects_movement_id' is null then null else (mv_map ->> (m ->> 'corrects_movement_id'))::uuid end,
        coalesce(actor, uid), (m ->> 'created_at')::timestamptz
      ) returning id into new_id;
      mv_map := mv_map || jsonb_build_object(m ->> 'id', new_id);
      bal := bal + (m ->> 'delta')::numeric;
      n_movements := n_movements + 1;
    end loop;
  end loop;

  -- Quantities: must equal the replayed history. Alert state is set first so restoring does not raise
  -- a low/out-of-stock alert for every product.
  for p in select value from jsonb_array_elements(coalesce(p_backup -> 'products', '[]'::jsonb)) loop
    continue when not prod_map ? (p ->> 'id');
    new_pid := (prod_map ->> (p ->> 'id'))::uuid;
    select coalesce(sum(delta), 0) into bal from public.stock_movements where product_id = new_pid;
    if bal <> coalesce((p ->> 'quantity')::numeric, 0) then
      raise exception 'The backup is inconsistent: % has quantity % but its history adds up to %. Nothing was restored.',
        p ->> 'name', p ->> 'quantity', trim_scale(bal) using errcode = '22023';
    end if;
    update public.product_alert_state
      set stock_state = case when bal <= 0 then 'out' when bal <= coalesce((p ->> 'min_stock')::numeric, 0) then 'low' else 'ok' end
      where product_id = new_pid;
    update public.products set quantity = bal where id = new_pid;
    if p ->> 'archived_at' is not null then
      update public.products set archived_at = (p ->> 'archived_at')::timestamptz where id = new_pid;
    end if;
  end loop;

  perform set_config('app.stock_write', 'off', true);

  insert into public.audit_logs (organization_id, actor_id, action, entity_type, details)
  values (p_org, uid, 'backup.restore', 'backup',
          jsonb_build_object('inventories', restored, 'products', n_products, 'movements', n_movements, 'backup_created_at', p_backup ->> 'created_at'));

  return jsonb_build_object('inventories', restored, 'products', n_products, 'movements', n_movements);
end $$;

-- -------------------------------------------------------------- integrations
-- Records THAT an integration is connected (and to which account/folder). No tokens or secrets are stored:
-- Google access tokens live only in the browser's memory and expire after about an hour.
create table public.integration_connections (
  organization_id uuid not null references public.organizations (id) on delete cascade,
  provider text not null check (provider in ('google_drive')),
  account_email text check (account_email is null or char_length(account_email) <= 254),
  folder_id text check (folder_id is null or char_length(folder_id) <= 200),
  connected_by uuid references public.profiles (id) on delete set null,
  connected_at timestamptz not null default now(),
  primary key (organization_id, provider)
);
alter table public.integration_connections enable row level security;
create policy integration_connections_select on public.integration_connections for select to authenticated
  using (public.has_org_role(organization_id, 'admin'));
revoke insert, update, delete, truncate on public.integration_connections from anon, authenticated;

create or replace function public.save_integration(p_org uuid, p_provider text, p_account text, p_folder text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.has_org_role(p_org, 'admin') then
    raise exception 'Only admins and owners can connect integrations' using errcode = '42501';
  end if;
  insert into public.integration_connections (organization_id, provider, account_email, folder_id, connected_by)
  values (p_org, p_provider, p_account, p_folder, auth.uid())
  on conflict (organization_id, provider)
  do update set account_email = excluded.account_email, folder_id = excluded.folder_id, connected_by = excluded.connected_by, connected_at = now();
  insert into public.audit_logs (organization_id, actor_id, action, entity_type, details)
  values (p_org, auth.uid(), 'integration.connect', 'integration', jsonb_build_object('provider', p_provider, 'account', p_account));
end $$;

create or replace function public.remove_integration(p_org uuid, p_provider text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.has_org_role(p_org, 'admin') then
    raise exception 'Only admins and owners can disconnect integrations' using errcode = '42501';
  end if;
  delete from public.integration_connections where organization_id = p_org and provider = p_provider;
  insert into public.audit_logs (organization_id, actor_id, action, entity_type, details)
  values (p_org, auth.uid(), 'integration.disconnect', 'integration', jsonb_build_object('provider', p_provider));
end $$;

